// Values arrive as real USD numbers from the bank (per the frozen /api/seller-finance contract).
// Format as dollars — never guess-divide by 100, which would misreport money.
function fmtUSD(n) {
  const v = Number(n);
  if (!Number.isFinite(v)) return "$0";
  return "$" + v.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

// Payout amounts arrive as integer CENTS (the seller_payouts / seller_balance contract). Divide by
// 100 to get USD dollars — this is the ONLY place cents→dollars happens for the payouts section.
function fmtCents(c) {
  const v = Number(c);
  if (!Number.isFinite(v)) return "$0";
  return fmtUSD(v / 100);
}

// first_paid_at -> short local date (defensive: bad/empty dates degrade to the em-dash).
function fmtDate(s, lang, none) {
  if (!s) return none;
  const d = new Date(s);
  if (isNaN(d.getTime())) return none;
  const loc = { pt: "pt-BR", en: "en-US", es: "es-ES", hi: "en-IN" }[lang] || "en-US";
  return d.toLocaleDateString(loc, { day: "2-digit", month: "short", year: "numeric" });
}

function Tile({ icon, label, value, dot }) {
  return (
    <div className="rounded-2xl border border-white/10 bg-white/[0.04] p-4">
      <div className="flex items-center gap-2 text-[11.5px] font-bold text-g-muted">
        <span className="inline-block h-2 w-2 rounded-full" style={{ background: dot, boxShadow: `0 0 10px ${dot}` }} />
        <span>{icon} {label}</span>
      </div>
      <div className="mt-1.5 text-[26px] font-black leading-none text-g-word tabular-nums">{value}</div>
    </div>
  );
}

export default function SellerFinance({ lang = "pt", seller, market = "us", nav }) {
  const t = T[lang] || T.pt;
  const [data, setData] = useState(null);   // null = loading · {} object = loaded
  const [err, setErr] = useState(false);
  const [showStmt, setShowStmt] = useState(false);
  const [pay, setPay] = useState(null);     // null = loading · { balance, payouts } · { error:true }
  const busy = useRef(false);
  const busyPay = useRef(false);

  const load = async () => {
    if (!seller?.email || busy.current) return;
    busy.current = true;
    setErr(false);
    try {
      const r = await fetch("/api/seller-finance", {
        method: "POST", headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          seller_email: seller.email, seller_code: seller.code || "",
          seller: { name: seller.name, email: seller.email, ref: seller.ref, code: seller.code },
        }),
      });
      const d = await r.json().catch(() => ({}));
      if (d && d.ok) setData(d);
      else { setData((prev) => prev || { totals: {}, ledger: [] }); setErr(true); }
    } catch {
      setData((prev) => prev || { totals: {}, ledger: [] }); setErr(true);
    } finally {
      busy.current = false;
    }
  };

  // Payouts (💸 Repasses) — own load: the seller's balance due + payout history, scoped to them by
  // the endpoint's auth (never the body). Honest empty/error states; never fabricates money.
  const loadPay = async () => {
    if (!seller?.email || busyPay.current) return;
    busyPay.current = true;
    try {
      const r = await fetch("/api/seller-payouts", {
        method: "POST", headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          action: "mine",
          seller_email: seller.email, seller_code: seller.code || "",
          seller: { name: seller.name, email: seller.email, ref: seller.ref, code: seller.code },
        }),
      });
      const d = await r.json().catch(() => ({}));
      if (d && d.ok) setPay({ balance: d.balance || {}, payouts: Array.isArray(d.payouts) ? d.payouts : [] });
      else setPay((prev) => (prev && prev.balance ? prev : { error: true }));
    } catch {
      setPay((prev) => (prev && prev.balance ? prev : { error: true }));
    } finally {
      busyPay.current = false;
    }
  };

  // LIVE — refreshes itself every 60s + on tab focus, so the seller's money is always current
  // without a single tap, on the phone or anywhere.
  useEffect(() => {
    if (!seller?.email) return;
    load(); loadPay();
    const iv = setInterval(() => { load(); loadPay(); }, 60000);
    const onFocus = () => { load(); loadPay(); };
    window.addEventListener("focus", onFocus);
    return () => { clearInterval(iv); window.removeEventListener("focus", onFocus); };
  }, [seller?.email]); // eslint-disable-line react-hooks/exhaustive-deps

  const totals = data?.totals || {};
  const pct = Number(data?.pct);
  const pctLabel = Number.isFinite(pct) ? (Number.isInteger(pct) ? String(pct) : pct.toFixed(1)) : "—";
  // ledger sorted by commission desc — the seller's biggest earners first.
  const ledger = useMemo(() => {
    const rows = Array.isArray(data?.ledger) ? data.ledger.slice() : [];
    rows.sort((a, b) => (Number(b.commission) || 0) - (Number(a.commission) || 0));
    return rows;
  }, [data]);

  const hasMoney = ledger.length > 0 || Number(totals.commission) > 0 || Number(totals.paid) > 0;

  // period = earliest → latest first_paid_at across the ledger (for the printed statement header).
  const period = useMemo(() => {
    const dates = ledger.map((r) => r.first_paid_at).filter(Boolean).map((s) => new Date(s)).filter((d) => !isNaN(d.getTime()));
    if (!dates.length) return null;
    const min = new Date(Math.min(...dates)), max = new Date(Math.max(...dates));
    return { min: min.toISOString(), max: max.toISOString() };
  }, [ledger]);

  // Print ONLY the statement doc: reuse the shared `printing-quote`/`quote-print-area` print CSS
  // (index.css) so nothing but the accounting document reaches the page — no extra styles needed.
  const printStmt = () => {
    document.body.classList.add("printing-quote");
    const done = () => { document.body.classList.remove("printing-quote"); window.removeEventListener("afterprint", done); };
    window.addEventListener("afterprint", done);
    setTimeout(() => window.print(), 40);
  };

  return (
    <div className="rounded-2xl border border-g-green/25 bg-g-green/[0.04] p-5">
      <div className="flex items-center justify-between gap-3">
        <div className="text-sm font-extrabold text-g-green">{t.title}</div>
        <button type="button" onClick={() => { load(); loadPay(); }} className="rounded-full border border-white/15 px-3 py-1 text-[11.5px] font-bold text-g-muted hover:text-g-word">{t.refresh}</button>
      </div>
      <p className="mt-1 text-[12.5px] text-g-muted max-w-2xl">{t.sub}</p>

      {/* loading skeletons */}
      {data === null && (
        <div className="mt-4 grid gap-3 sm:grid-cols-3">
          {[0, 1, 2].map((i) => <div key={i} className="h-[86px] animate-pulse rounded-2xl border border-white/10 bg-white/[0.03]" />)}
        </div>
      )}

      {data !== null && !hasMoney && (
        <>
          {err && <div className="mt-3 text-[12.5px] text-g-gold">{t.err}</div>}
          <div className="mt-4 rounded-2xl border border-dashed border-white/15 bg-white/[0.02] p-6 text-center">
            <div className="text-3xl">💵</div>
            <div className="mt-1.5 text-[13.5px] font-extrabold text-g-word">{t.empty}</div>
            <p className="mx-auto mt-1 max-w-md text-[12.5px] leading-relaxed text-g-muted">{t.emptyHint}</p>
            {typeof nav === "function" && (
              <button type="button" onClick={() => nav("alvos")} className="btn-bright mt-4 text-[13px]">{t.emptyCta}</button>
            )}
          </div>
        </>
      )}

      {data !== null && hasMoney && (
        <>
          {/* 3 big tiles — signal dots: green (commission, done/money), gold (paid), orange (Gui) */}
          <div className="mt-4 grid gap-3 sm:grid-cols-3">
            <Tile icon="💵" label={t.tCommission} value={fmtUSD(totals.commission)} dot="#3E9468" />
            <Tile icon="💰" label={t.tPaid} value={fmtUSD(totals.paid)} dot="#D6C29A" />
            <Tile icon="🤝" label={t.tClients} value={String(Number(totals.clients) || ledger.length || 0)} dot="#FF8A33" />
          </div>

          {/* honest note — commission is a % of REAL client payments; always shown in USD */}
          <p className="mt-2.5 text-[11.5px] leading-relaxed text-g-muted">
            {t.note.replace("{pct}", pctLabel)}{market === "br" ? ` ${t.usdNote}` : ""}
          </p>
          {err && <div className="mt-2 text-[12px] text-g-gold">{t.err}</div>}

          {/* per-client ledger, biggest commission first */}
          <div className="mt-4">
            <div className="flex items-center justify-between gap-3">
              <div className="text-[11px] font-black uppercase tracking-wide text-g-gold">{t.ledger}</div>
              <button type="button" onClick={() => setShowStmt(true)} className="rounded-full border border-g-green/35 bg-g-green/[0.10] px-3 py-1 text-[11.5px] font-bold text-g-green hover:bg-g-green/20">{t.gen}</button>
            </div>
            <div className="mt-2 overflow-x-auto rounded-xl border border-white/10">
              <table className="w-full min-w-[460px] text-left text-[12.5px]">
                <thead>
                  <tr className="bg-white/[0.04] text-[10.5px] font-black uppercase tracking-wider text-g-muted">
                    <th className="px-3 py-2">{t.colBiz}</th>
                    <th className="px-3 py-2 text-right">{t.colPaid}</th>
                    <th className="px-3 py-2 text-right">{t.colComm}</th>
                    <th className="px-3 py-2 text-right">{t.colSince}</th>
                  </tr>
                </thead>
                <tbody>
                  {ledger.map((r, i) => (
                    <motion.tr key={(r.client_email || "") + i} initial={{ opacity: 0 }} animate={{ opacity: 1 }} transition={{ duration: 0.25, delay: Math.min(i * 0.03, 0.3) }}
                      className="border-t border-white/[0.06]">
                      <td className="px-3 py-2">
                        <div className="font-bold text-g-word">{r.business || r.client_email || t.none}</div>
                        {r.business && r.client_email && <div className="text-[10.5px] text-g-muted">{r.client_email}</div>}
                      </td>
                      <td className="px-3 py-2 text-right tabular-nums text-g-ink">{fmtUSD(r.paid)}</td>
                      <td className="px-3 py-2 text-right tabular-nums font-bold text-g-green">{fmtUSD(r.commission)}</td>
                      <td className="px-3 py-2 text-right whitespace-nowrap text-g-muted">{fmtDate(r.first_paid_at, lang, t.none)}</td>
                    </motion.tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>
        </>
      )}

      {/* 💸 Repasses — saldo devido (âmbar se >0, verde zerado) + histórico honesto. Always shown once
          the seller is loaded; honest loading/error/empty states, never fabricated money. */}
      <div className="mt-5 rounded-2xl border border-white/10 bg-white/[0.02] p-4">
        <div className="text-[13px] font-extrabold text-g-word">{t.repTitle}</div>
        <p className="mt-0.5 text-[11.5px] text-g-muted">{t.repSub}</p>

        {pay === null && <div className="mt-3 h-[68px] animate-pulse rounded-xl border border-white/10 bg-white/[0.03]" />}
        {pay && pay.error && <div className="mt-3 text-[12px] text-g-gold">{t.repErr}</div>}

        {pay && pay.balance && (() => {
          const due = Number(pay.balance.due_cents) || 0;
          const paidOut = Number(pay.balance.paid_out_cents) || 0;
          const owes = due > 0; // âmbar quando devendo, verde quando zerado
          const credit = due < 0; // ajuste/estorno após a troca — nunca mostrar "$-X" como "tudo em dia"
          return (
            <>
              <div className="mt-3 grid gap-3 sm:grid-cols-2">
                <div className={`rounded-2xl border p-4 ${owes ? "border-g-gold/35 bg-g-gold/[0.06]" : "border-g-green/30 bg-g-green/[0.05]"}`}>
                  <div className="flex items-center gap-2 text-[11.5px] font-bold text-g-muted">
                    <span className="inline-block h-2 w-2 rounded-full" style={{ background: owes ? "#FFC23D" : "#3E9468", boxShadow: `0 0 10px ${owes ? "#FFC23D" : "#3E9468"}` }} />
                    <span>{t.due}</span>
                  </div>
                  <div className={`mt-1.5 text-[26px] font-black leading-none tabular-nums ${owes ? "text-g-gold" : "text-g-green"}`}>{fmtCents(credit ? 0 : due)}</div>
                  {!owes && !credit && <div className="mt-1 text-[11px] font-semibold text-g-green">{t.allPaid}</div>}
                  {credit && <div className="mt-1 text-[11px] font-semibold text-g-muted">Ajuste de estorno/transferência aplicado ({fmtCents(due)}) — nada a receber no momento.</div>}
                </div>
                <div className="rounded-2xl border border-white/10 bg-white/[0.04] p-4">
                  <div className="flex items-center gap-2 text-[11.5px] font-bold text-g-muted">
                    <span className="inline-block h-2 w-2 rounded-full" style={{ background: "#D6C29A", boxShadow: "0 0 10px #D6C29A" }} />
                    <span>{t.paidOut}</span>
                  </div>
                  <div className="mt-1.5 text-[26px] font-black leading-none text-g-word tabular-nums">{fmtCents(paidOut)}</div>
                </div>
              </div>

              <div className="mt-4">
                <div className="text-[11px] font-black uppercase tracking-wide text-g-gold">{t.repHist}</div>
                {pay.payouts.length === 0 ? (
                  <div className="mt-2 rounded-xl border border-dashed border-white/12 bg-white/[0.02] p-4 text-center text-[12px] text-g-muted">{t.repEmpty}</div>
                ) : (
                  <div className="mt-2 overflow-x-auto rounded-xl border border-white/10">
                    <table className="w-full min-w-[380px] text-left text-[12.5px]">
                      <thead>
                        <tr className="bg-white/[0.04] text-[10.5px] font-black uppercase tracking-wider text-g-muted">
                          <th className="px-3 py-2">{t.colWhen}</th>
                          <th className="px-3 py-2 text-right">{t.colValue}</th>
                          <th className="px-3 py-2">{t.colNote}</th>
                        </tr>
                      </thead>
                      <tbody>
                        {pay.payouts.map((p, i) => (
                          <tr key={(p.id || "") + i} className="border-t border-white/[0.06]">
                            <td className="px-3 py-2 whitespace-nowrap text-g-muted">{fmtDate(p.created_at, lang, t.none)}</td>
                            <td className="px-3 py-2 text-right tabular-nums font-bold text-g-green">{fmtCents(p.amount_cents)}</td>
                            <td className="px-3 py-2 text-g-ink">{p.period || p.note || t.none}</td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                )}
              </div>
            </>
          );
        })()}
      </div>

      {/* printable accounting statement — a clean light document the seller keeps for their records */}
      {showStmt && (
        <div className="fixed inset-0 z-50 flex items-start justify-center overflow-y-auto bg-black/70 p-4 backdrop-blur-sm" onClick={() => setShowStmt(false)}>
          <div className="my-6 w-full max-w-[720px]" onClick={(e) => e.stopPropagation()}>
            <div className="mb-2 flex items-center justify-end gap-2">
              <button type="button" onClick={printStmt} className="btn-bright text-[13px]">{t.print}</button>
              <button type="button" onClick={() => setShowStmt(false)} className="rounded-full border border-white/25 bg-white/10 px-4 py-2 text-[13px] font-bold text-g-word hover:bg-white/20">{t.close}</button>
            </div>
            {/* light doc — bg white / dark ink so print + screen both read like real accounting paper */}
            <div className="quote-print-area rounded-2xl bg-white p-7 text-[#1a1a1a] shadow-lift" style={{ fontFamily: "Inter, system-ui, sans-serif" }}>
              <div className="flex items-start justify-between border-b border-black/10 pb-4">
                <div>
                  <div className="text-[19px] font-black text-[#111]">🌱 Guileo</div>
                  <div className="text-[13px] font-bold text-[#333]">{t.stmtTitle}</div>
                </div>
                <div className="text-right text-[11px] text-[#555]">
                  <div>{t.generated}: {fmtDate(new Date().toISOString(), lang, "—")}</div>
                  {period && <div>{t.period}: {fmtDate(period.min, lang, "—")} {t.until} {fmtDate(period.max, lang, "—")}</div>}
                </div>
              </div>

              <div className="mt-4 text-[12.5px] text-[#333]">
                <div><span className="font-bold text-[#111]">{t.seller}:</span> {seller?.name || "—"}</div>
                {seller?.email && <div className="text-[#555]">{seller.email}{seller?.ref ? ` · ref ${seller.ref}` : ""}</div>}
              </div>

              {/* totals block */}
              <div className="mt-5 grid grid-cols-2 gap-3 sm:grid-cols-4">
                {[
                  [t.totalComm, fmtUSD(totals.commission)],
                  [t.totalPaid, fmtUSD(totals.paid)],
                  [t.clientsPaid, String(Number(totals.clients) || ledger.length || 0)],
                  [t.rate, pctLabel === "—" ? "—" : `${pctLabel}%`],
                ].map(([lab, val], i) => (
                  <div key={i} className="rounded-lg border border-black/10 bg-black/[0.02] p-2.5">
                    <div className="text-[9.5px] font-bold uppercase tracking-wide text-[#777]">{lab}</div>
                    <div className="mt-0.5 text-[15px] font-black text-[#111] tabular-nums">{val}</div>
                  </div>
                ))}
              </div>

              {/* ledger table */}
              <table className="mt-5 w-full text-left text-[12px]">
                <thead>
                  <tr className="border-b-2 border-black/20 text-[10px] font-black uppercase tracking-wide text-[#666]">
                    <th className="py-1.5 pr-2">{t.colBiz}</th>
                    <th className="py-1.5 px-2 text-right">{t.colPaid}</th>
                    <th className="py-1.5 px-2 text-right">{t.colComm}</th>
                    <th className="py-1.5 pl-2 text-right">{t.colSince}</th>
                  </tr>
                </thead>
                <tbody>
                  {ledger.map((r, i) => (
                    <tr key={(r.client_email || "") + i} className="border-b border-black/[0.07]">
                      <td className="py-1.5 pr-2 font-semibold text-[#222]">{r.business || r.client_email || t.none}</td>
                      <td className="py-1.5 px-2 text-right tabular-nums text-[#333]">{fmtUSD(r.paid)}</td>
                      <td className="py-1.5 px-2 text-right tabular-nums font-bold text-[#111]">{fmtUSD(r.commission)}</td>
                      <td className="py-1.5 pl-2 text-right whitespace-nowrap text-[#555]">{fmtDate(r.first_paid_at, lang, t.none)}</td>
                    </tr>
                  ))}
                </tbody>
                <tfoot>
                  <tr className="border-t-2 border-black/20 text-[12.5px] font-black text-[#111]">
                    <td className="py-2 pr-2">Σ</td>
                    <td className="py-2 px-2 text-right tabular-nums">{fmtUSD(totals.paid)}</td>
                    <td className="py-2 px-2 text-right tabular-nums text-[#0a6b3f]">{fmtUSD(totals.commission)}</td>
                    <td className="py-2 pl-2" />
                  </tr>
                </tfoot>
              </table>

              <p className="mt-5 border-t border-black/10 pt-3 text-[10px] leading-relaxed text-[#888]">{t.stmtFoot}</p>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
